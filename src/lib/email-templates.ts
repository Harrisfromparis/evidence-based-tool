export const createSensoryChecklistEmail = (data: {
  studentName: string
  completedBy: string
  observations: {
    visual: { seeks: string[]; avoids: string[]; notes: string }
    auditory: { seeks: string[]; avoids: string[]; notes: string }
    tactile: { seeks: string[]; avoids: string[]; notes: string }
    proprioceptive: { seeks: string[]; avoids: string[]; notes: string }
    vestibular: { seeks: string[]; avoids: string[]; notes: string }
    olfactoryGustatory: { seeks: string[]; avoids: string[]; notes: string }
  }
  recommendations: string
  timestamp: number
}): EmailTemplate => {
  const subject = `Sensory Needs Checklist - ${data.studentName}`
  
  const formatSensoryCategory = (category: string, data: { seeks: string[]; avoids: string[]; notes: string }) => {
    return `
${category.toUpperCase()}:
  Seeks:
    ${data.seeks.length > 0 ? data.seeks.map(s => `• ${s}`).join('\n    ') : '• None noted'}
  
  Avoids:
    ${data.avoids.length > 0 ? data.avoids.map(s => `• ${s}`).join('\n    ') : '• None noted'}
  
  Additional Notes: ${data.notes || 'None'}
`
  }
  
  const body = `SENSORY NEEDS CHECKLIST
${createTextDivider('=')}

Generated: ${formatDateForEmail(data.timestamp)}
Student: ${data.studentName}
Completed by: ${data.completedBy}

${createSectionHeader('SENSORY OBSERVATIONS')}
${formatSensoryCategory('Visual', data.observations.visual)}
${formatSensoryCategory('Auditory', data.observations.auditory)}
${formatSensoryCategory('Tactile', data.observations.tactile)}
${formatSensoryCategory('Proprioceptive', data.observations.proprioceptive)}
${formatSensoryCategory('Vestibular', data.observations.vestibular)}
${formatSensoryCategory('Olfactory/Gustatory', data.observations.olfactoryGustatory)}

${createSectionHeader('RECOMMENDATIONS')}
${data.recommendations}

${APP_SIGNATURE}`

  return { subject, body }
}

