export const createCombinedReportEmail = (data: {
  studentName: string
  parentAssessment?: any
  studentAssessment?: any
  schoolPlan?: any
  sensoryChecklist?: any
  behaviourAnalyses?: any[]
  timestamp: number
}): EmailTemplate => {
  const subject = `Comprehensive Support Report - ${data.studentName}`
  
  let body = `COMPREHENSIVE SUPPORT REPORT
${createTextDivider('=')}

Generated: ${formatDateForEmail(data.timestamp)}
Student: ${data.studentName}

This report combines multiple assessments and plans to provide a holistic view of support needs and strategies.

`

  if (data.parentAssessment) {
    body += `${createSectionHeader('PARENT/CARER PERSPECTIVE')}
Completed by: ${data.parentAssessment.parentName}

Key Priorities:
${data.parentAssessment.priorities.map((p: string, i: number) => `${i + 1}. ${p}`).join('\n')}

`
  }

  if (data.studentAssessment) {
    body += `${createSectionHeader('STUDENT PERSPECTIVE')}
Preferred Supports:
${data.studentAssessment.preferredSupports.map((s: string, i: number) => `${i + 1}. ${s}`).join('\n')}

Overall Feedback: ${data.studentAssessment.overallFeedback}

`
  }

  if (data.sensoryChecklist) {
    body += `${createSectionHeader('SENSORY PROFILE SUMMARY')}
Key sensory needs have been identified across multiple domains.
Detailed sensory checklist available in separate document.

`
  }

  if (data.schoolPlan) {
    body += `${createSectionHeader('CURRENT SCHOOL SUPPORT PLAN')}
Plan Type: ${data.schoolPlan.planType}
Review Date: ${data.schoolPlan.reviewDate}
Team Members: ${data.schoolPlan.teamMembers.length}

`
  }

  if (data.behaviourAnalyses && data.behaviourAnalyses.length > 0) {
    body += `${createSectionHeader('BEHAVIOUR COMMUNICATION ANALYSES')}
${data.behaviourAnalyses.length} behaviour analysis/analyses completed.
Key themes identified in separate documents.

`
  }

  body += `${createSectionHeader('RECOMMENDATIONS')}
This combined report should be reviewed collaboratively by the full support team, including the student and family where appropriate.

All supports should be:
• Evidence-based
• Student-centred
• Regularly reviewed and adjusted
• Implemented with dignity and autonomy

${APP_SIGNATURE}`

  return { subject, body }
}

